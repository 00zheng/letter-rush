import { createHash } from "node:crypto";
import { existsSync } from "node:fs";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { gunzipSync } from "node:zlib";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const sourceArchive = path.join(
  projectRoot,
  "dictionary",
  "source",
  "enable2k.txt.gz",
);
const allowedPath = path.join(projectRoot, "dictionary", "custom-allowed.txt");
const blockedPath = path.join(projectRoot, "dictionary", "custom-blocked.txt");
const outputDirectory = path.join(
  projectRoot,
  "src",
  "generated",
  "dictionary",
);
const normalizedOutput = path.join(
  projectRoot,
  "dictionary",
  "generated",
  "enable2k-af52415-v1.txt",
);
const sqlOutputArgument = process.argv.find((argument) =>
  argument.startsWith("--sql-output="),
);
const sqlOutput = sqlOutputArgument
  ? path.resolve(projectRoot, sqlOutputArgument.slice("--sql-output=".length))
  : null;

const VERSION = "enable2k-af52415-v1";
const SOURCE_COMMIT = "af52415c13af809bd8757a40f17f46e79d09583c";
const SOURCE_ARCHIVE_SHA256 =
  "2c1093669cd16439bdb0a693a0058626c9c9f82e59244c9b0bde89515d44d3ad";
const VALID_WORD = /^[a-z]+$/;

function parseOverrideFile(contents, fileName) {
  const words = new Set();

  for (const rawLine of contents.split(/\r?\n/u)) {
    const normalized = rawLine.trim().toLowerCase();
    if (!normalized || normalized.startsWith("#")) continue;
    if (!VALID_WORD.test(normalized)) {
      throw new Error(`${fileName} contains a malformed entry: ${rawLine}`);
    }
    words.add(normalized);
  }

  return words;
}

if (!existsSync(sourceArchive)) {
  throw new Error(
    "Missing dictionary/source/enable2k.txt.gz. Restore the pinned source archive before generating.",
  );
}

const [archive, allowedContents, blockedContents] = await Promise.all([
  readFile(sourceArchive),
  readFile(allowedPath, "utf8"),
  readFile(blockedPath, "utf8"),
]);
const archiveSha256 = createHash("sha256").update(archive).digest("hex");
if (archiveSha256 !== SOURCE_ARCHIVE_SHA256) {
  throw new Error(
    `Pinned dictionary archive checksum mismatch: expected ${SOURCE_ARCHIVE_SHA256}, received ${archiveSha256}.`,
  );
}

const sourceContents = gunzipSync(archive).toString("ascii");
const allowedWords = parseOverrideFile(allowedContents, "custom-allowed.txt");
const blockedWords = parseOverrideFile(blockedContents, "custom-blocked.txt");
const words = new Set();

for (const rawWord of sourceContents.split(/\r?\n/u)) {
  const word = rawWord.trim().toLowerCase();
  if (word.length >= 2 && VALID_WORD.test(word) && !blockedWords.has(word)) {
    words.add(word);
  }
}

for (const word of allowedWords) {
  if (!blockedWords.has(word)) words.add(word);
}

const sortedWords = [...words].sort();
const normalizedContents = `${sortedWords.join("\n")}\n`;
const sha256 = createHash("sha256").update(normalizedContents).digest("hex");

await rm(outputDirectory, { force: true, recursive: true });
await mkdir(outputDirectory, { recursive: true });
await mkdir(path.dirname(normalizedOutput), { recursive: true });

const importEntries = [];
for (const letter of "abcdefghijklmnopqrstuvwxyz") {
  const bucket = sortedWords.filter((word) => word.startsWith(letter));
  await writeFile(
    path.join(outputDirectory, `${letter}.ts`),
    `// Generated by scripts/generate-dictionary.mjs. Do not edit.\nconst words =\n  ${JSON.stringify(bucket.join("\n"))};\nexport default words;\n`,
  );
  importEntries.push(
    `  ${letter}: () => import("./${letter}").then((module) => module.default),`,
  );
}

await writeFile(
  path.join(outputDirectory, "index.ts"),
  `// Generated by scripts/generate-dictionary.mjs. Do not edit.
export const GENERATED_DICTIONARY_METADATA = {
  version: ${JSON.stringify(VERSION)},
  sourceCommit: ${JSON.stringify(SOURCE_COMMIT)},
  wordCount: ${sortedWords.length},
  sha256: ${JSON.stringify(sha256)},
} as const;

export const GENERATED_DICTIONARY_BUCKETS = {
${importEntries.join("\n")}
} as const;
`,
);
await writeFile(normalizedOutput, normalizedContents);

if (sqlOutput) {
  await mkdir(path.dirname(sqlOutput), { recursive: true });
  await writeFile(
    sqlOutput,
    `-- Generated by scripts/generate-dictionary.mjs from pinned ENABLE 2K.
-- Do not edit this generated data migration manually.
-- Security-sensitive: this exact sync targets only the immutable dictionary
-- version below. The private table remains inaccessible to browser roles.
begin;

create temporary table letter_rush_dictionary_sync (
  word text primary key
) on commit drop;

insert into letter_rush_dictionary_sync (word)
select source.word
from unnest(
  string_to_array(
    trim(both E'\\n' from $enable2k$
${normalizedContents}$enable2k$),
    E'\\n'
  )
) as source(word);

do $dictionary_source_assertion$
begin
  if (select count(*) from letter_rush_dictionary_sync) <> ${sortedWords.length} then
    raise exception 'Dictionary source count does not match ${VERSION}.';
  end if;

  if not exists (
    select 1
    from letter_rush_dictionary_sync
    where word = 'crate'
  ) then
    raise exception 'Dictionary source is missing required regression word: crate.';
  end if;
end
$dictionary_source_assertion$;

insert into private.approved_words (dictionary_version, word)
select '${VERSION}', source.word
from letter_rush_dictionary_sync as source
on conflict (dictionary_version, word) do nothing;

delete from private.approved_words as approved
where approved.dictionary_version = '${VERSION}'
  and not exists (
    select 1
    from letter_rush_dictionary_sync as source
    where source.word = approved.word
  );

do $dictionary_target_assertion$
begin
  if (
    select count(*)
    from private.approved_words
    where dictionary_version = '${VERSION}'
  ) <> ${sortedWords.length} then
    raise exception 'Approved dictionary count does not match ${VERSION}.';
  end if;

  if not exists (
    select 1
    from private.approved_words
    where dictionary_version = '${VERSION}'
      and word = 'crate'
  ) then
    raise exception 'Approved dictionary is missing required regression word: crate.';
  end if;
end
$dictionary_target_assertion$;

commit;
`,
  );
}

process.stdout.write(
  `Generated ${sortedWords.length.toLocaleString("en-US")} words for ${VERSION} (${sha256.slice(0, 12)}).${sqlOutput ? ` SQL: ${path.relative(projectRoot, sqlOutput)}` : ""}\n`,
);
